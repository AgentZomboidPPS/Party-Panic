"""Prints where the crates of the Hollow Night pile go, as the Luau table World/SeasonWorld places
real Hollow Crate meshes from (the pile's own mesh leaves them out: its simplification flattened
their lids into roofs). Each is the crate's CFrame in Roblox studs relative to the pile's bottom
centre (Blender's (x, y, z) is Roblox's (-x, z, y), as tools/meshgen/season/export.py writes it) and
its scale. Run it with Blender's Python after changing the pile, and paste the table in:

    /home/user/bpyenv/bin/python tools/meshgen/season/pile_crates.py
"""

import math
import sys
from pathlib import Path

import bpy
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import blender_lib  # noqa: E402

blender_lib.EXPORT = True
import hollow_night as HN  # noqa: E402

# Blender -> Roblox: (x, y, z) -> (-x, z, y)
B = np.array([[-1, 0, 0], [0, 0, 1], [0, 1, 0]], dtype=float)


def euler_xyz(rx, ry, rz):
    cx, sx, cy, sy, cz, sz = math.cos(rx), math.sin(rx), math.cos(ry), math.sin(ry), math.cos(rz), math.sin(rz)
    X = np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]])
    Y = np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]])
    Z = np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]])
    return Z @ Y @ X


def main():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    record = []
    HN.crate_pile(game=True, crates=False, record=record)
    print("-- (generated by tools/meshgen/season/pile_crates.py)")
    print("local PILE_CRATES = {")
    for loc, scale, rot in record:
        p = B @ np.array(loc, dtype=float)
        r = B @ euler_xyz(*rot) @ B.T
        values = [*p, *r.flatten()]
        print("\t{ CFrame.new(" + ", ".join(f"{v:.4f}" for v in values) + f"), {scale:.2f} }},")
    print("}")


if __name__ == "__main__":
    main()
