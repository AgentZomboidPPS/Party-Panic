"""Writes Last Dancer's chart (src/shared/LastDancerChart.luau) from the song that plays it.

Owner: "Let's make it" (the Last Dancer rhythm game). The chart is the song's own lead line: every note
the lead plays in tools/music/songs/LastDancer.py (CHART_BARS) is a note the dancers have to tap, so the
game and the music can't drift apart. Run it again after changing a bar:

    python3 tools/music/lastdancer_chart.py            # write src/shared/LastDancerChart.luau
    python3 tools/music/lastdancer_chart.py --check    # fail if that file is out of date

It also checks the chart against the rules of the round (src/shared/Logic/LastDancer.luau): notes sit on
eighth notes, none is closer than an eighth to the one before, and nothing falls in the last beat of a
phrase that ends with a cut.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "src" / "shared" / "LastDancerChart.luau"
sys.path.insert(0, str(HERE))


def load_song_module():
    spec = importlib.util.spec_from_file_location("songs.LastDancer", HERE / "songs" / "LastDancer.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def build(module) -> str:
    notes = module.chart_notes()
    beat = 60 / module.BPM
    problems = []
    previous = -1.0
    for t, lane, bar in notes:
        if not 1 <= lane <= 4:
            problems.append(f"bar {bar}: lane {lane}")
        if abs((t / (beat / 2)) - round(t / (beat / 2))) > 1e-6:
            problems.append(f"bar {bar}: {t}s is not on an eighth note")
        if previous >= 0 and t - previous < beat / 2 - 1e-6:
            problems.append(f"bar {bar}: {t}s is closer than an eighth to the note before")
        previous = t
    phrase_seconds = beat * 16
    for t, lane, bar in notes:
        phrase = int(t // phrase_seconds) + 1  # 1-based
        into = t - (phrase - 1) * phrase_seconds
        if 2 <= phrase <= 7 and into >= phrase_seconds - beat - 1e-6:
            problems.append(f"bar {bar}: a note in the last beat of phrase {phrase}, which ends with a cut")
    if notes and notes[-1][0] > beat * 4 * len(module.CHART_BARS) - 0.5:
        problems.append("the last note is too close to the buzzer")
    if problems:
        raise SystemExit("the chart breaks the rules:\n  " + "\n  ".join(problems))
    lines = [
        "--!strict",
        "-- GENERATED by tools/music/lastdancer_chart.py from tools/music/songs/LastDancer.py - do not edit by hand.",
        "-- Last Dancer's chart: every note the song's lead plays, as seconds after GO and a lane 1-4",
        f"-- (the chord's root, third, fifth and octave). {len(notes)} notes at {module.BPM} bpm.",
        "",
        "local Notes: { { T: number, Lane: number } } = {",
    ]
    for t, lane, _bar in notes:
        lines.append(f"\t{{ T = {t:.3f}, Lane = {lane} }},")
    lines += ["}", "", f"return {{ Bpm = {module.BPM}, Notes = Notes }}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = build(load_song_module())
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is out of date: run tools/music/lastdancer_chart.py")
        print("chart up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
