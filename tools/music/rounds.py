"""Renders, checks and encodes every mini-game's own round track (owner: "put in the backlog custom
music for each mini game").

    python3 tools/music/rounds.py                      # every track
    python3 tools/music/rounds.py --only FireRope,SharkBait --preview /tmp/music
    python3 tools/music/rounds.py --check-only          # render and check, write nothing

Songs come from modes.py (SONGS) and from tools/music/songs/<ModeId>.py, each of which defines
`SONG = Song(...)` with modes.py's helpers. Adding a mini-game's track is one new file there.

For each track this writes assets/audio/rounds/<ModeId>.ogg (and an MP3 preview with --preview),
and rewrites src/shared/RoundMusic.luau with every track's drop time (the end of its intro, which
AudioController lines up with the round's GO) and length. The asset ids live in
src/shared/AudioAssets.luau (Rounds), filled in by tools/upload_assets.py --what rounds.

Checks (a track that fails one is reported and not written):
  - the intro is at least 13 s (the rules card and the 3-2-1 play over it);
  - after the drop there's at least the round's Duration of music (GameDefinitions), up to
    LONGEST seconds: a longer round (Honey Trap's turns can run 150 s) loops it seamlessly;
  - loudness within 0.5 LU of -11 LUFS, true peak at most -1 dBTP;
  - the loop seam: the jump from the last sample to the first is no bigger than the music's own
    sample-to-sample movement;
  - phone speakers: how much of the low end sits under 80 Hz (reported; a warning past 35%).
"""

from __future__ import annotations

import argparse
import importlib
import re
import sys
import tempfile
from pathlib import Path

import numpy as np
from scipy import signal

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

import modes  # noqa: E402
import score  # noqa: E402
import synth as s  # noqa: E402

OUT = ROOT / "assets" / "audio" / "rounds"
TABLE = ROOT / "src" / "shared" / "RoundMusic.luau"
DEFINITIONS = ROOT / "src" / "shared" / "GameDefinitions.luau"

MIN_INTRO = 13.0
LONGEST = 90.0
TARGET_LUFS = -11.0
MAX_TRUE_PEAK = -1.0


def songs() -> list:
    found = {song.id: song for song in modes.SONGS}
    for path in sorted((HERE / "songs").glob("*.py")):
        if path.stem.startswith("_"):
            continue
        module = importlib.import_module(f"songs.{path.stem}")
        song = getattr(module, "SONG", None)
        if song is None:
            raise SystemExit(f"{path.name} has no SONG")
        if song.id in found:
            raise SystemExit(f"two songs for {song.id}")
        found[song.id] = song
    return list(found.values())


def durations() -> dict[str, float]:
    text = DEFINITIONS.read_text()
    out = {}
    for block in re.finditer(r'Id = "(\w+)",(.*?)\n\t}', text, re.S):
        match = re.search(r"Duration = ([\d.]+)", block.group(2))
        if match:
            out[block.group(1)] = float(match.group(1))
    return out


def seam_ratio(audio: np.ndarray) -> float:
    """The jump across the loop point against the 99.9th percentile of ordinary sample steps."""
    steps = np.abs(np.diff(audio, axis=1))
    typical = float(np.percentile(steps, 99.9)) + 1e-9
    jump = float(np.max(np.abs(audio[:, 0] - audio[:, -1])))
    return jump / typical


def low_share(audio: np.ndarray) -> float:
    mono = audio.mean(axis=0)
    freqs, power = signal.welch(mono, s.SR, nperseg=8192)
    total = power[freqs >= 20].sum() + 1e-12
    return float(power[(freqs >= 20) & (freqs < 80)].sum() / total)


def check(song, audio: np.ndarray, track, duration: float | None) -> tuple[dict, list[str]]:
    length = audio.shape[1] / s.SR
    drop = song.intro * track.bar
    info = {
        "length": length,
        "drop": drop,
        "lufs": score.lufs(audio),
        "peak": score.true_peak_db(audio),
        "seam": seam_ratio(audio),
        "low": low_share(audio),
    }
    problems = []
    if drop < MIN_INTRO - 1e-6:
        problems.append(f"intro {drop:.1f}s < {MIN_INTRO:.0f}s")
    if duration is None:
        problems.append("no Duration in GameDefinitions")
    elif length - drop < min(duration, LONGEST):
        problems.append(f"{length - drop:.1f}s after the drop < the round's {min(duration, LONGEST):.0f}s")
    if abs(info["lufs"] - TARGET_LUFS) > 0.5:
        problems.append(f"loudness {info['lufs']:.1f} LUFS")
    if info["peak"] > MAX_TRUE_PEAK + 1e-6:
        problems.append(f"true peak {info['peak']:.2f} dBTP")
    if info["seam"] > 1.0:
        problems.append(f"loop seam jump {info['seam']:.2f}x")
    return info, problems


def write_table(rows: dict[str, dict]):
    lines = [
        "-- GENERATED by tools/music/rounds.py - do not edit by hand.",
        "-- Every mini-game's own round track: when its drop lands (seconds from the start: the end of",
        "-- its intro, which AudioController lines up with the round's GO) and how long it is (it loops).",
        "",
        "return {",
    ]
    for mode_id in sorted(rows):
        row = rows[mode_id]
        lines.append(f'\t{mode_id} = {{ Title = "{row["title"]}", Drop = {row["drop"]:.3f}, Length = {row["length"]:.3f} }},')
    lines.append("}")
    TABLE.write_text("\n".join(lines) + "\n")


def read_table() -> dict[str, dict]:
    rows = {}
    if TABLE.exists():
        for match in re.finditer(r'(\w+) = \{ Title = "(.*?)", Drop = ([\d.]+), Length = ([\d.]+) \}', TABLE.read_text()):
            rows[match.group(1)] = {"title": match.group(2), "drop": float(match.group(3)), "length": float(match.group(4))}
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", help="comma-separated mode ids")
    parser.add_argument("--preview", type=Path, help="also write MP3 previews into this folder")
    parser.add_argument("--check-only", action="store_true", help="render and check, write nothing")
    parser.add_argument("--list", action="store_true", help="list the songs and the modes without one")
    args = parser.parse_args()

    all_songs = songs()
    lengths = durations()
    if args.list:
        have = {song.id for song in all_songs}
        for song in all_songs:
            print(f"{song.id:16s} {song.title:28s} {song.bpm:5.0f} bpm  intro {song.intro} bars, {song.bars} bars")
        missing = sorted(set(lengths) - have)
        print(f"\n{len(have)} songs; modes without one: {', '.join(missing) or 'none'}")
        return 0

    only = set(args.only.split(",")) if args.only else None
    OUT.mkdir(parents=True, exist_ok=True)
    if args.preview:
        args.preview.mkdir(parents=True, exist_ok=True)
    rows = read_table()
    failed = 0
    with tempfile.TemporaryDirectory() as tmp:
        for song in all_songs:
            if only and song.id not in only:
                continue
            audio, track = song.render()
            info, problems = check(song, audio, track, lengths.get(song.id))
            print(
                f"{song.id:16s} {info['length']:5.1f}s drop {info['drop']:5.2f}s  {info['lufs']:6.2f} LUFS"
                f"  {info['peak']:6.2f} dBTP  seam {info['seam']:.2f}x  <80Hz {info['low'] * 100:4.1f}%"
                + (f"  !! {'; '.join(problems)}" if problems else "  ok")
                + ("  (warning: heavy low end for phones)" if info["low"] > 0.35 else "")
            )
            if problems:
                failed += 1
                continue
            if args.check_only:
                continue
            wav = Path(tmp) / f"{song.id}.wav"
            s.write_wav(wav, audio)
            s.encode(wav, OUT / f"{song.id}.ogg", "ogg")
            if args.preview:
                s.encode(wav, args.preview / f"{song.id}.mp3", "mp3")
            rows[song.id] = {"title": song.title, "drop": info["drop"], "length": info["length"]}
    if not args.check_only:
        write_table(rows)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
